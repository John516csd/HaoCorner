export type MusicMessage = keyof typeof english;
export type MusicTranslator = (key: MusicMessage, values?: Values) => string;
export function isMusicLocale(value: unknown): value is MusicLocale { return value === 'zh' || value === 'en'; }
export function messageKey(error: unknown, fallback: MusicMessage): MusicMessage {
  const key = error instanceof Error ? error.message : error;
  return typeof key === 'string' && Object.hasOwn(english, key) ? key as MusicMessage : fallback;
}
export function translate(locale: MusicLocale, key: MusicMessage, values: Values = {}) {
  const entry = locale === 'en' ? english[key] : key;
  const text = typeof entry === 'function' ? entry(values) : entry;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => values[name] === undefined ? match : String(values[name]));
}

export function artistDisplayName(artist: { name: string; english: string }, locale: MusicLocale) {
  if (locale === 'zh' || !/[\u3400-\u9fff]/u.test(artist.name)) return artist.name;
  return artist.english.split(' ').map(word => word.includes('.') ? word : word[0] + word.slice(1).toLowerCase()).join(' ');
}
